"""The rolling block (LEVEL3B items 49 and 50) and the moving bar (LEVEL4 items 75 to 78, LEVEL10A item 12), oracle
against port, schema 4 (oracle host.patch hunks 25 and 26; docs/specs/wall/objects-missing.md sections 2.1, 3 and 6).

The reference source built no controller for either (item.h INIT_ITEM left both as plain items), so the blocks never
raised their sectors and never slid, and the bars never moved and were not solid. Cases, each compared tick for tick
through the streaming pipes:

block (LEVEL3B)
  slide-74, slide-76  Lara placed in front of the switch (74 -> block 49, 76 -> block 50), one ACTION press: the block is
                      activated by the trigger (tick 47), goes state 0 -> 2 (animation 244 -> 246, 64 units a frame along
                      its facing for 32 frames) -> 1 (245) and stops 2048 units away at the centre of a sector. The sector
                      hash (`world[0]`) changes on the tick the slide begins (the start cell is restored) and on the tick
                      it ends (the arrival cell is raised), and nowhere else.
  toggle-74           the switch pressed twice: the block slides back (246 -> 247 -> 244) and the sector hash returns to
                      its value before the first press: the floor changes are exactly undone.
  solid-49, solid-50  Lara placed in the hall next to the block's start cell, running at it: the cell is solid from the
                      first tick (she is stopped at its wall). The previous oracle lets her run into it.
  walk-49             one script of 564 ticks (LEVEL3B allows 4096): the switch, a walk off the ledge into the hall, into
                      the cell the block left (open: she stands in it at y = 8704) and east along the row into the cell the
                      block arrived in (solid: she stops at its wall, x = 68507 = the cell edge 68608 minus her radius).
                      The same inputs on the previous oracle: the block never moves, the cell she wanted is open.
  save-slide          a save and a load (real source gameSave/gameLoad) after the slide and in the middle of it: both
                      programs equal, and the sector hash after the load equals the one before (the load raises the cell
                      the block stands in, and not the cell of a block that is sliding).
  flip-19             Lara placed on the map-flip pad of room 19 (floor-data trigger action 3, flip map 0) with both blocks
                      still at their start cells: the flip rebuilds every sector (`game_world_flip`, worldRebuildDerivedState
                      ForFlip) and both programs agree afterwards, so the block cells are raised again after a flip. No walk
                      reaches a flip pad from the hall (`reach`), so a flip AFTER a slide is not shown by play.
bar (LEVEL4 and LEVEL10A)
  keys-N              LEVEL4: Lara placed at keyhole 80..83, the four keys given, each put into its keyhole from the ring: the
                      bar 78..75 plays its animation (274 -> 276 -> 275, 36 frames).
  bar-walls           LEVEL4: Lara placed south of the bars, running at them with all four closed: stopped at the stack
                      (solid); with the four keys inserted the way is free. The previous oracle lets her through either way.
  switch-5            LEVEL10A: the switch pulled, the bar's animation 235 -> 236 -> 237 -> 238 moves it along its facing
                      (the animation's speed), its room following.

negative  the block cases on the previous oracle (`--old-oracle`, m6-gaps2b) on the same inputs: it must differ from the port at tick 0
          (the raised cells) and in the outcome of the walk cases; the bar cases on the oracle without hunk 26
          (`--bar-control-oracle`, `test/oracle/control.sh no-hunk-26`: the published m6-gaps2b caps every scene at 600 ticks and
          LEVEL4's key script is 1,882): the bars do not move and Lara walks through them.

Run with PYTHONPATH=tools/cook:test/game:
  movers.py --executable HOST --oracle ORACLE --old-oracle OLD --bar-control-oracle NO26 --out DIR [block|bar|negative|reach|all]
"""
