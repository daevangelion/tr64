def bar_verdicts(case, result, watch):
    if result.get('status') != 'equal':
        return [f"not equal: {result.get('status')} {result.get('field', '')} {result.get('expected', '')} {result.get('actual', '')}"]
    bad = []
    name = case['name']
    if name == 'keys-4':
        for bar in case['bars']:
            seq = [s[1:] for s in watch.seq(bar)]
            if seq != [(0, 0, 274), (0, 1, 276), (1, 1, 275)]:
                bad.append(f'bar {bar}: sequence {seq}')
        x, y, z = watch.rows[-1]['lara']
        if not (x < 30 * 1024):
            bad.append(f'Lara did not pass the doorway: {(x, y, z)}')
    if name == 'closed-4':
        x, y, z = watch.rows[-1]['lara']
        if not (30850 <= x <= 31000) or not (38300 <= z <= 38500):
            bad.append(f'Lara not stopped by the closed plates: {(x, y, z)}')
    if name == 'switch-5':
        seq = [s[3] for s in watch.seq(12)]
        if [a for i, a in enumerate(seq) if i == 0 or a != seq[i - 1]] != [235, 236, 237, 238, 239]:
            bad.append(f'animation sequence {seq}')
        last = watch.last_item(12)
        rooms = {it[5] for r in watch.rows for it in [r['items'].get(12)] if it}
        if last is None or not (last[4][0] < 50500 and rooms == {13, 10}):
            bad.append(f'bar did not move along its facing into room 10: {last}, rooms {rooms}')
    if name == 'solid-12':
        x, y, z = watch.rows[-1]['lara']
        if not (53400 <= x <= 53600):
            bad.append(f'Lara not stopped by the bar: x={x}')
    return bad


def do_bar(args, report):
    env4, env10 = env_for('level4', args), env_for('level10a', args)
    ok = True
    for case in bar_cases(env4, env10):
        env = env4 if case['level'] == 'level4' else env10
        d.Script.LIMIT = 4096
        result, watch = run(env, case, case['bars'])
        bad = bar_verdicts(case, result, watch)
        row = dict(name=case['name'], status=result.get('status'), ticks=len(case['masks']), failures=bad)
        if watch.rows:
            row['bars'] = {b: (watch.seq(b), watch.last_item(b)) for b in case['bars']}
            row['hash_changes'] = watch.hash_changes()
            row['lara_last'] = watch.rows[-1]['lara']
        if args.action in ('negative', 'all') and not bad:
            old = old_series(args, case['level'], case, case['bars'], oracle=args.bar_control_oracle)
            row['negative'] = dict(old_lara_last=old.rows[-1]['lara'], old_bar_sequences={b: old.seq(b) for b in case['bars']},
                                   differs=old.rows[-1]['lara'] != watch.rows[-1]['lara'] or
                                   any(old.seq(b) != watch.seq(b) for b in case['bars']))
            if not row['negative']['differs']:
                row['failures'].append('the previous oracle shows no difference')
        report['bar'].append(row)
        ok &= not row['failures']
        print(json.dumps(row, default=str), flush=True)
    return ok


def reach(args):
    env = env_for('level3b', args)
    for name, tx, tz in (('hall -> flip pads', 45, 62), ('hall -> room 5', 71, 60)):
        seen = _bfs(env, 27, C(66), C(46), lambda x, z: (x, z) == (tx, tz) or abs(x - tx) + abs(z - tz) < 2)
        print(name, 'reachable' if seen is True else f'not reachable ({seen} cells reached)')


def _bfs(env, room, x, z, goal, up=800, down=4096, limit=40000):
    cell = lambda a: a >> 10
    first = d.ground(env, room, x, z, None, clear=1024)
    k0 = (cell(x), cell(z))
    seen = {k0: first}
    queue = collections.deque([k0])
    while queue and len(seen) < limit:
        k = queue.popleft()
        r, y = seen[k]
        if goal(*k):
            return True
        for dx, dz, _ in d.DIRS:
            nk = (k[0] + dx, k[1] + dz)
            if nk in seen:
                continue
            g = d.ground(env, r, C(nk[0]), C(nk[1]), None, clear=1024)
            if g is None or g[1] < y - up or g[1] > y + down:
                continue
            seen[nk] = g
            queue.append(nk)
    return len(seen)


