C = lambda cell: cell * 1024 + 512


def expand(runs):
    return [m for m, n in runs for _ in range(n)]


class Watch:
    """Per-tick summary over records already proven equal (or over probe records)."""
    def __init__(self, indices=()):
        self.indices = set(indices)
        self.rows = []

    def __call__(self, row):
        lara = row['lara']
        self.rows.append(dict(
            tick=row['tick'],
            world=row['world'][0] if row.get('world') else None,
            pairs=row['world'][3] if row.get('world') else None,
            flipped=row['save']['flipped'],
            lara=tuple(lara['pos']) if lara else None, health=lara['health'] if lara else None,
            items={a['index']: (a['state'], a['goal'], a['anim'], a['frame'], tuple(a['pos']), a['room'])
                   for a in row['active'] if a['index'] in self.indices}))

    def feed(self, rows):
        for row in rows:
            self(row)
        return self

    def seq(self, index):
        """[(first tick, state, goal, anim)] of an item in the active list."""
        out = []
        for r in self.rows:
            it = r['items'].get(index)
            if it and (not out or out[-1][1:] != it[:3]):
                out.append((r['tick'],) + it[:3])
        return out

    def last_item(self, index):
        for r in reversed(self.rows):
            if index in r['items']:
                return r['items'][index]
        return None

    def hash_changes(self):
        """[(tick, hash)] where world[0] changes (tick 0 included)."""
        out = []
        for r in self.rows:
            if not out or out[-1][1] != r['world']:
                out.append((r['tick'], r['world']))
        return out


def env_for(level, args, old=False):
    return d.Env(level, args.executable, oracle=args.old_oracle if old else args.oracle)


def switch_start(env, switch):
    return items.hole_starts(env, env.level.data['items'][switch])[0][2]


def run(env, case, indices):
    watch = Watch(indices)
    try:
        result = d.compare(env, case['start'], case['masks'], ticks=len(case['masks']), observe=watch,
                           setup=case.get('setup', ()), save=case.get('save'))
    except ValueError as error:
        return dict(status='error', why=str(error)[:200]), watch
    return result, watch


def old_series(args, level, case, indices, oracle=None):
    """The negative control's series: `oracle` (the bars' control without hunk 26; the published m6-gaps2b cannot run LEVEL4's
    long scene) or `--old-oracle`."""
    env = d.Env(level, args.executable, oracle=oracle or args.old_oracle)
    rows = d.probe(env, case['start'], case['masks'], want='all', setup=case.get('setup', ()))
    return Watch(indices).feed(rows)


# ---- the rolling block ---------------------------------------------------

def slide_case(env, block):
    return dict(name=f'slide-{BLOCKS[block]}', block=block, start=switch_start(env, BLOCKS[block]),
                masks=[ACTION] * 8 + [NONE] * 120)


def toggle_case(env):
    return dict(name='toggle-74', block=49, start=switch_start(env, 74),
                masks=[ACTION] * 8 + [NONE] * 120 + [ACTION] * 8 + [NONE] * 120)


def solid_case(env, block):
    """In the hall, one cell from the block's start cell on the side the block does not slide to, running at it."""
    it = env.level.data['items'][block]
    if block == 49:
        x, z, yaw = C(66), C(45), -16384        # block (65, 45) slides +x; Lara comes from the east, facing -x
    else:
        x, z, yaw = C(70), C(49), -32768        # block (70, 48) slides -z; Lara comes from the south, facing -z
    g = d.ground(env, it['room'], x, z, it['y'], 0, clear=1024)
    return dict(name=f'solid-{block}', block=block, start=(g[0], x, g[1], z, yaw), masks=[FORWARD] * 90 + [NONE] * 10)


def walk_case(env):
    return dict(name='walk-49', block=49, start=switch_start(env, 74), masks=expand(WALK_49))


def save_case(env, when):
    base = slide_case(env, 49)
    return dict(name=f'save-slide-{when}', block=49, start=base['start'], masks=base['masks'], save=(when, when + 1))


def flip_case(env):
    g = d.ground(env, 19, C(45), C(62), None, clear=512)
    return dict(name='flip-19', block=49, start=(g[0], C(45), g[1], C(62), 0), masks=[NONE] * 40)


def regenerate(env):
    """The closed-loop generation of WALK_49 on the oracle (about 1,500 oracle runs)."""
    d.Script.LIMIT = 4096
    s = d.Script(env, switch_start(env, 74))
    s.hold(ACTION, 8)
    if not s.until(lambda r: any(a['index'] == 49 and a['state'] == 1 for a in r['active']), NONE, 150, chunk=8):
        raise ValueError('block 49 did not slide')
    for cell in ((64, 48), (66, 48), (66, 46), (65, 45)):
        if not s.walk_to(C(cell[0]), C(cell[1]), tol=300, limit=300, run=True, chunk=6):
            raise ValueError(f'walk to {cell} failed')
    s.hold(NONE, 10)
    s.walk_to(C(68), C(45), tol=150, limit=150, run=True, chunk=6, stuck=6)    # stopped by the block: returns False
    s.hold(NONE, 10)
    runs = []
    for m in s.masks:
        if runs and runs[-1][0] == m:
            runs[-1][1] += 1
        else:
            runs.append([m, 1])
    return runs


def block_verdicts(case, result, watch):
    bad = []
    if result.get('status') != 'equal':
        return [f"not equal: {result.get('status')} {result.get('field', '')} {result.get('expected', '')} {result.get('actual', '')}"]
    name, b = case['name'], case['block']
    if watch.rows and any(r['pairs'] != 1 for r in watch.rows):
        bad.append('world validator verdict not 1')
    if name.startswith('slide-'):
        seq = [s[1:] for s in watch.seq(b)]
        if seq != [(0, 0, 244), (2, 1, 246), (1, 1, 245)]:
            bad.append(f'state sequence {seq}')
        ticks = {s[1]: s[0] for s in watch.seq(b)}
        start, end = ROLL[b]
        last = watch.last_item(b)
        if last is None or last[4][0::2] != end:
            bad.append(f'final position {last}')
        changes = [t for t, _ in watch.hash_changes()]
        # tick 0 -> 1: the doors' first update (every level has it); then restore at the slide's first tick, raise at its end
        slide_first = [s[0] for s in watch.seq(b) if s[1] == 2][0]
        slide_end = [s[0] for s in watch.seq(b) if s[1] == 1][0]
        if slide_first not in changes or slide_end not in changes:
            bad.append(f'sector hash changes at {changes}, slide {slide_first}..{slide_end}')
        if len([t for t in changes if t > 1]) != 2:
            bad.append(f'sector hash changed {len([t for t in changes if t > 1])} times after tick 1, expected 2 ({changes})')
    if name == 'toggle-74':
        seq = [s[1:] for s in watch.seq(b)]
        want = [(0, 0, 244), (2, 1, 246), (1, 1, 245), (2, 0, 247), (0, 0, 244)]
        if seq != want:
            bad.append(f'state sequence {seq}')
        ch = watch.hash_changes()
        if len(ch) < 4 or ch[-1][1] != ch[1][1]:
            bad.append(f'sector hash did not return: {ch}')
        last = watch.last_item(b)
        if last is None or last[4][0::2] != ROLL[b][0]:
            bad.append(f'final position {last}')
    if name.startswith('solid-'):
        x, y, z = watch.rows[-1]['lara']
        if b == 49 and not (67584 <= x <= 67584 + 150):
            bad.append(f'Lara not stopped at the wall of cell 65: x={x}')
        if b == 50 and not (50176 <= z <= 50176 + 150):
            bad.append(f'Lara not stopped at the wall of cell (70, 48): z={z}')
    if name == 'walk-49':
        x, y, z = watch.rows[-1]['lara']
        at_open = [r for r in watch.rows if r['lara'] and abs(r['lara'][0] - C(65)) < 150 and abs(r['lara'][2] - C(45)) < 300 and r['lara'][1] == 8704]
        if not at_open:
            bad.append('Lara never stood in the cell the block left')
        if not (SOLID_X - 20 <= x <= SOLID_X + 20) or y != 8704:
            bad.append(f'Lara not stopped by the block in its new cell: {(x, y, z)}')
    if name.startswith('save-slide'):
        ch = watch.hash_changes()
        if [h for _, h in ch].count(ch[-1][1]) < 1 or len(ch) < 4:
            bad.append(f'hash changes {ch}')
        # across the save/load boundary the hash at the load tick equals the one before it
        t = case['save'][1]
        before = [r['world'] for r in watch.rows if r['tick'] == t - 1][0]
        after = [r['world'] for r in watch.rows if r['tick'] == t + 1][0]
        if name.endswith('100') and before != after:
            bad.append(f'sector hash changed across the load: {before} -> {after}')
    if name == 'flip-19':
        flips = [r['flipped'] for r in watch.rows]
        if flips[0] != 0 or flips[-1] != 1:
            bad.append(f'flip state {flips[0]} -> {flips[-1]}')
        ch = watch.hash_changes()
        if len(ch) < 2:
            bad.append(f'sector hash did not change at the flip: {ch}')
    return bad


def old_differs(args, level, case, indices, new_watch):
    """The negative control: what the previous oracle does on the same inputs."""
    old = old_series(args, level, case, indices)
    out = dict(first_tick_hash_differs=old.rows[0]['world'] != new_watch.rows[0]['world'] if new_watch.rows else None)
    name = case['name']
    if name.startswith('solid-') or name == 'walk-49':
        out['old_final_lara'] = old.rows[-1]['lara']
        out['new_final_lara'] = new_watch.rows[-1]['lara']
        out['differs'] = old.rows[-1]['lara'] != new_watch.rows[-1]['lara']
    elif name.startswith('slide-') or name == 'toggle-74':
        out['old_block_sequence'] = old.seq(case['block'])
        out['differs'] = old.seq(case['block']) != new_watch.seq(case['block'])
    else:
        out['differs'] = out['first_tick_hash_differs']
    return out


def do_block(args, report):
    env = env_for('level3b', args)
    d.Script.LIMIT = 4096
    cases = [slide_case(env, 49), slide_case(env, 50), toggle_case(env), solid_case(env, 49), solid_case(env, 50),
             walk_case(env), save_case(env, 100), save_case(env, 60), flip_case(env)]
    ok = True
    for case in cases:
        result, watch = run(env, case, (49, 50))
        bad = block_verdicts(case, result, watch)
        row = dict(name=case['name'], status=result.get('status'), ticks=len(case['masks']), failures=bad)
        if watch.rows:
            row['hash_changes'] = watch.hash_changes()
            row['block_sequence'] = watch.seq(case['block'])
            row['lara_last'] = watch.rows[-1]['lara']
        if args.action in ('negative', 'all') and not bad:
            row['negative'] = old_differs(args, 'level3b', case, (49, 50), watch)
            if not row['negative']['differs']:
                row['failures'].append('the previous oracle shows no difference')
        report['block'].append(row)
        ok &= not row['failures']
        print(json.dumps(row, default=str), flush=True)
    return ok


# ---- the moving bar --------------------------------------------------------

KEYS = {80: (129, 1, 78), 81: (130, 2, 77), 82: (131, 3, 76), 83: (132, 4, 75)}     # keyhole -> (key pickup, slot, bar)
GIVE4 = [('give', t, 1) for t, _, _ in KEYS.values()]


USE_KEY = 42            # Lara state while a key goes into its keyhole


def hole_start(env, hole):
    """Lara 420 units in front of the keyhole, facing it (the keyhole accepts her 312..512 away, within 200 sideways)."""
    return [c for c in items.hole_starts(env, env.level.data['items'][hole]) if c[0] == 420 and c[1] == 0][0][2]


def insert_key(s, slot):
    s.hold(NONE, 3)
    d.open_ring(s)
    if not d.ring_pick(s, slot, page_keys=True):
        raise ValueError(f'the ring did not select key {slot}')
    if not s.until(lambda r: r['lara']['state'] == USE_KEY, NONE, 120, chunk=2):
        raise ValueError(f'key {slot}: Lara never began the insertion (not at the keyhole)')
    if not s.until(lambda r: r['lara']['state'] == 2 and r['inventory']['state'] == 0, NONE, 260, chunk=4):
        raise ValueError(f'key {slot}: the insertion did not finish')


def keys_script(env):
    """Closed loop on the oracle: Lara at keyhole 80 with the four keys given, each put into its keyhole (stepping from hole
    to hole: the walk's stop slides about 180 units, so each leg aims short of the hole's start by that and then checks
    Lara began the USE_KEY state), then through the doorway the bars closed: (30, 38) -> (30, 37) -> (29, 37). Returns [mask, ticks] runs."""
    d.Script.LIMIT = 4096
    I = env.level.data['items']
    holes = list(KEYS)
    s = d.Script(env, hole_start(env, holes[0]), setup=GIVE4)
    for n, hole in enumerate(holes):
        if n:
            st = hole_start(env, hole)
            for _ in range(4):
                here = s.lara()['pos']
                sign = 1 if st[3] > here[2] else -1
                if not s.walk_to(st[1], st[3] - sign * 130, tol=45, limit=400, run=False, chunk=2, stuck=30):
                    raise ValueError('walk to the next keyhole failed')
                s.hold(NONE, 14)
                pos = s.lara()['pos']
                if abs(pos[2] - st[3]) <= 150 and abs(pos[0] - st[1]) <= 100:
                    break
            else:
                raise ValueError(f'could not settle at keyhole {hole}: {s.lara()["pos"]} for {st[1:4:2]}')
            if not d.face(s, I[hole]['x'] + 8000, st[3], tol=300, limit=60):
                raise ValueError('turn to the keyhole failed')
            s.hold(NONE, 8)
        insert_key(s, KEYS[hole][1])
    s.hold(NONE, 60)
    for cell in ((30, 38), (30, 37), (29, 37)):
        s.walk_to(C(cell[0]), C(cell[1]), tol=200, limit=200, run=False, chunk=4)
    s.hold(NONE, 10)
    runs = []
    for m in s.masks:
        if runs and runs[-1][0] == m:
            runs[-1][1] += 1
        else:
            runs.append([m, 1])
    return runs


