"""Write gate_place.h: two placements in the gate level, derived from the player's data.
The source is the pack's: --source pc reads <data>/<level>.phd, --source psx
<data>/PSXDATA/<LEVEL>.PSX (the same IR, so one derivation for both).

RUN   the centre of a flat, plain, dry patch of 3x3 sectors (no floor data, no pit or ceiling hole, 3 blocks of
      headroom, in a room without items if any has one) for the pace gate: Lara runs a circle (about 560 units across
      at the fixed game's run turn rate) there for ten seconds without meeting a wall or a ledge.
END   the first sector whose floor data holds an END action (test/game/cuts.py
      end_triggers, the placement the end-of-level oracle scripts use).
DEATH the sealed dry sector with the tallest free fall; Lara is placed one click
      below its ceiling, so she falls its whole height. A fall of seven blocks
      killed Lara on the host game (health 0 after about 55 ticks).
The header lands in the gate build's generated directory; nothing derived from
the data is committed."""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / "tools/cook"), str(ROOT / "test/game")]
sys.dont_write_bytecode = True
import src_pc  # noqa: E402
import src_psx  # noqa: E402
from cuts import end_triggers  # noqa: E402


def placements(level):
    ends = end_triggers(level)
    if not ends:
        raise SystemExit("gate level has no END trigger sector")
    best = None
    for index, room in enumerate(level.rooms):
        if room.flags & 1:  # water room: the fall would end in water
            continue
        for i, sector in enumerate(room.sectors):
            if -127 in (sector["floor"], sector["ceiling"]) or sector["room_below"] != 255 or sector["room_above"] != 255:
                continue
            drop = (sector["floor"] - sector["ceiling"]) * 256
            x = room.info["x"] + (i // room.z_sectors) * 1024 + 512
            z = room.info["z"] + (i % room.z_sectors) * 1024 + 512
            candidate = (drop, index, x, sector["ceiling"] * 256 + 256, z)
            if best is None or candidate > best:
                best = candidate
    if best is None or best[0] < 6144:
        raise SystemExit("gate level has no fall tall enough to kill")
    return best, ends[0]


def run_placement(level):
    """(room, x, y, z) of the centre of the largest flat plain patch (radius 1, so 3x3 sectors)."""
    occupied = {item["room"] for item in level.data["items"]}
    best = None
    for index, room in enumerate(level.rooms):
        if room.flags & 1:
            continue
        zs, sectors = room.z_sectors, room.sectors
        xs = len(sectors) // zs

        def plain(xi, zi, ref=None):
            if not (0 <= xi < xs and 0 <= zi < zs):
                return None
            sector = sectors[xi * zs + zi]
            if (sector["floor"] == -127 or sector["floor_index"] or sector["room_below"] != 255
                    or sector["room_above"] != 255 or sector["floor"] - sector["ceiling"] < 12):
                return None
            return (sector["floor"], sector["ceiling"])

        for xi in range(1, xs - 1):
            for zi in range(1, zs - 1):
                centre = plain(xi, zi)
                if centre and all(plain(xi + dx, zi + dz) == centre for dx in range(-1, 2) for dz in range(-1, 2)):
                    candidate = (index not in occupied, centre[0] - centre[1], -index, xi, zi)
                    if best is None or candidate > best[0]:
                        best = (candidate, index, room, xi, zi, centre)
    if best is None:
        raise SystemExit("gate level has no flat plain 3x3 patch in a dry room")
    _, index, room, xi, zi, (floor, _) = best
    return index, room.info["x"] + xi * 1024 + 512, floor * 256, room.info["z"] + zi * 1024 + 512


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", choices=("pc", "psx"), default="pc")
    parser.add_argument("--data", type=Path, help="default /tmp/tr64/data/<source>")
    parser.add_argument("--level", default="level1")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    data = args.data or Path("/tmp/tr64/data") / args.source
    level = (src_pc.load(data / f"{args.level}.phd") if args.source == "pc"
             else src_psx.load(data / "PSXDATA" / f"{args.level.upper()}.PSX"))
    (drop, room, x, y, z), (end_room, ex, ey, ez) = placements(level)
    run_room, run_x, run_y, run_z = run_placement(level)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        "/* Generated by tools/ship/gate_place.py from the player's level data; not source. */\n"
        f'#define GATE_LEVEL "{args.level}"\n'
        f"#define GATE_DEATH {room}u,{x},{y},{z},0\n"
        f"#define GATE_END {end_room}u,{ex},{ey},{ez},0\n"
        f"#define GATE_RUN {run_room}u,{run_x},{run_y},{run_z},0\n")
    print(f"gate placements {args.source} {args.level}: death room {room} drop {drop}, end room {end_room}, run room {run_room}")


if __name__ == "__main__":
    main()
