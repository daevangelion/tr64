import argparse
import os
import pathlib
import re
import shutil
import subprocess
import tempfile
ROOT = pathlib.Path(__file__).resolve().parents[2]
EXEMPT = {"docs/PROVENANCE.md", "AGENTS.md"}
# Behaviour specifications written behind the wall (docs/PROVENANCE.md 2a): the
# header block, which names the source project, commit, files read, reader and
# date, may carry the forbidden project names; the body may not.
WALL = re.compile(r"docs/specs/wall/[^/]+\.md")
BINARY = {".bin", ".cue", ".iso", ".img", ".chd", ".exe", ".elf", ".o", ".a", ".z64", ".v64", ".n64", ".rom", ".phd", ".psx", ".pak", ".pack", ".tim", ".xa", ".vag", ".wav", ".ogg", ".mp3", ".str", ".mp4", ".png", ".ppm", ".jpg", ".jpeg", ".rbc", ".trace"}
SOURCE = {".c", ".cpp", ".h", ".hpp", ".def", ".s", ".ld", ".py", ".sh", ".mk"}


def git(root, *args):
    prefix = ["rtk", "proxy"] if shutil.which("rtk") else []
    return subprocess.check_output([*prefix, "git", "-C", str(root), *args], stderr=subprocess.STDOUT)


def forbidden_names(policy):
    section = policy.split("## 2.", 1)[1].split("- The retail", 1)[0]
    names = re.findall(r"`([^`]+)`", section)
    if not names:
        raise ValueError("policy has no forbidden names")
    return [re.compile(r"(?<!\w)" + re.escape(s) + r"(?!\w)", re.I) for s in names]


def wall_header_lines(lines):
    """Number of leading lines in the header block of a wall specification: up
    to the first blank line or the first `#` heading after line 1 (a heading on
    the first line is the title and belongs to the block)."""
    for i, line in enumerate(lines):
        if not line.strip() or (i and line.startswith("#")):
            return i
    return len(lines)


def check(path, content, names):
    p = pathlib.PurePosixPath(path)
    errors = []
    ext = p.suffix.casefold()
    if ext in BINARY or any(s.casefold() in {"data", "content", "fixtures", "screenshots", "traces"} for s in p.parts) or (ext in {".json", ".jsonl", ".csv"} and "trace" in p.stem.casefold()):
        errors.append("artifact path/type")
    if len(content) > 256 * 1024:
        errors.append("size exceeds 256 KiB")
    if content.startswith((b"MZ", b"\x7fELF", b"PS-X EXE", b"\0" + b"\xff" * 10 + b"\0")):
        errors.append("executable/disc signature")
    try:
        text = content.decode("utf-8")
    except UnicodeDecodeError:
        errors.append("non-UTF-8 binary")
        text = ""
    if b"\0" in content:
        errors.append("binary NUL")
    # Runtime-state CSV columns or a source-data hash plus trace ticks identify
    # derived oracle output. Synthetic inputs should be generated by source.
    if ext in {".json", ".jsonl", ".csv"} and ((re.search(r'"(?:level|source)_sha256"', text) and re.search(r'"(?:ticks|frames|trace)"', text)) or re.search(r"(?im)^tick,item,x,y,z(?:,|$)", text)):
        errors.append("derived runtime trace content")
    lines = text.splitlines()
    first = int(bool(lines and lines[0].startswith("#!")))
    source = ext in SOURCE or p.name.casefold() == "makefile" or bool(first)
    spdx = re.search(r"SPDX-License-Identifier:\s*([A-Za-z0-9.-]+)", lines[first] if len(lines) > first else "")
    bsd = path.startswith("game/") or (path.startswith("test/oracle/") and ext in {".c", ".cpp", ".h", ".hpp"}) or (path.startswith("tools/cook/") and spdx and spdx[1] == "BSD-2-Clause")
    expected = "BSD-2-Clause" if bsd else "MIT"
    if source and (not spdx or spdx[1] != expected):
        errors.append("missing/wrong SPDX")
    if source and bsd:
        notice = lines[first + 1] if len(lines) > first + 1 else ""
        if not all(s in notice for s in ("Derived from OpenLara", "2018", "Timur", "XProger", "Gagiev", "game/LICENSE-OPENLARA")) or not re.search(r"\b[0-9a-f]{8,40}\b", notice) or not re.search(r"(?:src|tools)/[\w./*-]+\.(?:cpp|h|c|py)\b", notice):
            errors.append("missing OpenLara source/revision notice")
    scanned = text
    if WALL.fullmatch(path):
        scanned = "\n".join(lines[wall_header_lines(lines):])
    if path not in EXEMPT and any(name.search(path + "\n" + scanned) for name in names):
        errors.append("forbidden project name")
    return errors


def scan(root, names, quiet=False):
    failures = []
    records = git(root, "ls-files", "--stage", "-z").split(b"\0")
    for record in filter(None, records):
        prefix, raw = record.split(b"\t", 1)
        mode, oid, stage = prefix.decode().split()
        path = raw.decode()
        if mode not in {"100644", "100755"} or stage != "0":
            failures.append((path, "index", "nonregular/unmerged index"))
            continue
        versions = [("index", git(root, "cat-file", "blob", oid))]
        work = root / path
        if work.is_symlink():
            failures.append((path, "worktree", "nonregular worktree"))
        elif work.is_file() and work.read_bytes() != versions[0][1]:
            versions.append(("worktree", work.read_bytes()))
        for version, content in versions:
            failures.extend((path, version, reason) for reason in check(path, content, names))
    if not quiet:
        for path, version, reason in failures:
            print(f"provcheck: {path} ({version}): {reason}")
        print(f"provcheck: {'FAIL' if failures else 'PASS'} ({len(records)-1} tracked files, index + worktree, {len(failures)} violations)")
    return failures


def selftest(names):
    good = b"/* SPDX-License-Identifier: MIT */\nint planted;\n"
    project = names[0].pattern.removeprefix(r"(?<!\w)").removesuffix(r"(?!\w)").replace("\\", "").encode()
    wall = b"# Plant\nProject: " + project + b", commit 0123abc\nFiles read: none\nReader: plant\nDate: 2026-11-18\n\n"
    cases = [("SPDX", "plant.c", b"int plant;\n", "missing/wrong SPDX"),
             ("uppercase source", "plant.C", b"int plant;\n", "missing/wrong SPDX"),
             ("extensionless script", "plant", b"#!/bin/sh\necho plant\n", "missing/wrong SPDX"),
             ("wrong SPDX", "plant.c", good.replace(b"MIT", b"GPL-3.0"), "missing/wrong SPDX"),
             ("game notice", "game/plant.h", good.replace(b"MIT", b"BSD-2-Clause"), "missing OpenLara source/revision notice"),
             ("oracle notice", "test/oracle/plant.cpp", good.replace(b"MIT", b"BSD-2-Clause"), "missing OpenLara source/revision notice"),
             ("cook notice", "tools/cook/plant.py", good.replace(b"MIT", b"BSD-2-Clause"), "missing OpenLara source/revision notice"),
             ("file type", "plant.PHD", good, "artifact path/type"),
             ("path", "data/plant.c", good, "artifact path/type"),
             ("size", "plant.c", good + b" " * (256 * 1024), "size exceeds 256 KiB"),
             ("name", "plant.c", good + project, "forbidden project name"),
             ("signature", "plant.c", b"\x7fELF" + good, "executable/disc signature"),
             ("binary NUL", "plant.c", good + b"\0", "binary NUL"),
             ("binary bytes", "plant.c", good + b"\xff", "non-UTF-8 binary"),
             ("trace", "result.csv", b"tick,item,x,y,z\n1,1,1,1,1\n", "derived runtime trace content"),
             ("wall body", "docs/specs/wall/plant.md", wall + b"\nBody names " + project + b".\n", "forbidden project name"),
             ("wall second heading", "docs/specs/wall/plant.md", wall.rstrip(b"\n") + b"\n## Behaviour\nBody names " + project + b".\n", "forbidden project name"),
             ("wall leading blank", "docs/specs/wall/plant.md", b"\n" + wall, "forbidden project name"),
             ("wall nested", "docs/specs/wall/sub/plant.md", wall, "forbidden project name"),
             ("wall non-markdown", "docs/specs/wall/plant.txt", wall, "forbidden project name"),
             ("header outside the wall", "docs/specs/plant.md", wall, "forbidden project name")]
    for header in (wall, wall.replace(b"\n\n", b"\n## Behaviour\n", 1), wall.replace(b"# Plant\n", b"", 1)):
        if check("docs/specs/wall/plant.md", header + b"Body without the name.\n", names):
            raise AssertionError("wall header with project name rejected")
    if not check("docs/specs/wall/plant.md", wall.replace(b"\n\n", b"\n", 1) + b"\n" + project + b"\n", names):
        raise AssertionError("wall header block ended without a blank line or heading")
    scratch = pathlib.Path(os.environ.get("TMPDIR", "/tmp/tr64/tmp/Skeleton"))
    scratch.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="provcheck-", dir=scratch) as temp:
        root = pathlib.Path(temp)
        git(root, "init", "-q")
        for label, path, bad, reason in cases:
            if bad == good:
                bad += b"\n"
            target = root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(good)
            git(root, "add", "--", path)
            target.write_bytes(bad)
            if (path, "worktree", reason) not in scan(root, names, True):
                raise AssertionError(label + " working reason escaped")
            git(root, "add", "--", path)
            target.write_bytes(good)
            if (path, "index", reason) not in scan(root, names, True):
                raise AssertionError(label + " index reason escaped")
            git(root, "rm", "--cached", "-f", "--", path)
            target.unlink()
            print(f"provcheck selftest rejected {label}: {reason} (index + worktree)")
        for ext in ("c", "cpp", "h", "py"):
            citation = f'/* SPDX-License-Identifier: BSD-2-Clause */\n/* Derived from OpenLara (c) 2018 Timur "XProger" Gagiev; see game/LICENSE-OPENLARA. tools/n64_magma/test_layout.{ext} 2333adef */\n'.encode()
            if check("tools/cook/plant.py", citation, names):
                raise AssertionError("permitted OpenLara citation rejected")
        if check("plant.c", good + b"/* prefix" + project + b"suffix extrxactor */", names):
            raise AssertionError("project name matched inside a word")
        target = root / "plant.c"
        target.write_bytes(good)
        git(root, "add", "--", "plant.c")
        target.unlink()
        target.symlink_to("absent")
        if ("plant.c", "worktree", "nonregular worktree") not in scan(root, names, True):
            raise AssertionError("symlink escaped")
    print(f"provcheck selftest PASS ({2*len(cases)+1} planted violations; permitted citations/word boundaries pass)")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--root", type=pathlib.Path, default=ROOT)
    ns = ap.parse_args()
    names = forbidden_names((ns.root / "docs/PROVENANCE.md").read_text())
    if ns.selftest:
        selftest(names)
        return 0
    return int(bool(scan(ns.root.resolve(), names)))


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, AssertionError, subprocess.CalledProcessError) as error:
        raise SystemExit(f"provcheck: checker failure: {error}")
